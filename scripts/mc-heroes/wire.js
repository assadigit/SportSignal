#!/usr/bin/env node
// scripts/mc-heroes/wire.js — sync src/pages/public.ts's DCL portrait maps
// from the registry (mc-heroes.json). GENERATED CODE — never hand-edit the
// MC-HEROES marked blocks; change the registry and re-run this.
//
//   node scripts/mc-heroes/wire.js           write (idempotent)
//   node scripts/mc-heroes/wire.js --check   verify sync (exit 1 on drift)
//
// What it generates (inside the DOMContentLoaded patch, AFTER the pinned
// bundle evaluated its own vars and BEFORE the async render reads them):
//   MC_ART      club -> {src: <home-variant file>}   (the bundle reads .src)
//   MC_GEOM     every variant file -> its fade stop
//   MC_SIDE     home-variant <-> away-twin swap map (both directions)
//   MC_HOME_SRC the set of home-variant srcs
//   mcFitScan   + the SIDE-AWARE SRC SWAP: an <img> whose src is the wrong
//               variant for its slot (.mc-port-h / .mc-port-a) is rewritten
//               to its twin pre-load — a fixture that flips a club to the
//               other side of the card can never render a head leaning
//               off-center. The swap falls through to the MC_GEOM lookup in
//               the same pass, so .mc-pre + --mcfade still apply pre-paint.
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const PAGE = path.join(ROOT, "src", "pages", "public.ts");
const REG = require("./mc-heroes.json");

// ---------- generated fragments ----------
function genMaps() {
  const art = Object.entries(REG.clubs)
    .map(([club, e]) => `"${club}":{src:"/ui/mc/${e.home}"}`)
    .join(",");
  const geom = Object.values(REG.clubs)
    .flatMap((e) => [["/ui/mc/" + e.home, e.fade], e.away ? ["/ui/mc/" + e.away, e.fade] : null])
    .filter(Boolean)
    .map(([f, fade]) => `"${f}":${fade}`)
    .join(",");
  const side = Object.values(REG.clubs)
    .flatMap((e) => [["/ui/mc/" + e.home, "/ui/mc/" + e.away], ["/ui/mc/" + e.away, "/ui/mc/" + e.home]])
    .filter((p) => p[0] && p[1])
    .map(([a, b]) => `"${a}":"${b}"`)
    .join(",");
  const homeSet = Object.values(REG.clubs)
    .map((e) => `"/ui/mc/${e.home}":1`)
    .join(",");
  return { art, geom, side, homeSet };
}

function genBlock() {
  const { geom, side, homeSet } = genMaps();
  return `/*MC-HEROES:AUTO-START (generated by scripts/mc-heroes/wire.js from mc-heroes.json — do not hand-edit)*/
/* v13.183-mchero (owner: the flawless mobile-heroes round): MC_GEOM now
   carries the fade stop of EVERY variant file (home + away twin); the new
   MC_SIDE / MC_HOME_SRC maps power the side-aware swap inside mcFitScan —
   the away slot of any fixture gets the mirrored twin automatically (a
   club flipping sides between fixtures can never render a head leaning
   off-center). Arsenal / Man City / Inter join MC_ART (canonical windows,
   generated + self-verified by the pipeline); Bayern moves to the
   canonical kane-3 pair (head 91px = every other canonical club — the
   legacy kane-2 30.3%W scale retired with this round). Sources + geometry
   snapshots: scripts/mc-heroes/mc-heroes.json; the pipeline gate lives in
   scripts/check-mc-heroes.js (npm test). */
var MC_GEOM={${geom}};
var MC_SIDE={${side}};
var MC_HOME_SRC={${homeSet}};
/*MC-HEROES:AUTO-END*/`;
}

function genScanHead() {
  return `var mcFitScan=function(){
/*MC-HEROES:SCAN-START (generated)*/
document.querySelectorAll(".hero-mcard .mc-port img").forEach(function(im){
var s0=im.getAttribute("src"),tw=MC_SIDE[s0];
if(tw){var po=im.closest(".mc-port");if(po){var wa=po.classList.contains("mc-port-a"),ih=!!MC_HOME_SRC[s0];if(wa===ih){im.setAttribute("src",tw);s0=tw}}}
var g=MC_GEOM[s0];`;
}
// ---------- the page surgery ----------
function readPage() { return fs.readFileSync(PAGE, "utf8"); }

function applyWrite(src) {
  let out = src;
  // 1) the AUTO block: replace the WHOLE marked region if present, else
  //    seed it at the first var MC_GEOM line (consuming it)
  const blockRe = /\/\*MC-HEROES:AUTO-START \(generated by scripts\/mc-heroes\/wire\.js[\s\S]*?\/\*MC-HEROES:AUTO-END\*\//;
  const geomRe = /var MC_GEOM=\{[^;]*\};/;
  if (blockRe.test(out)) out = out.replace(blockRe, "@@MC_HEROES_BLOCK@@");
  else {
    if (!geomRe.test(out)) throw new Error("MC_GEOM not found in public.ts");
    out = out.replace(geomRe, "@@MC_HEROES_BLOCK@@");
  }

  // 2) the standalone MC_ART re-assignment (its original position, between
  //    the historical comments — updated in place, idempotent: the
  //    generated line matches the same regex)
  const artRe = /if\(typeof MC_ART!=="undefined"\)MC_ART=\{[^;]*\};/;
  if (!artRe.test(out)) throw new Error("MC_ART assignment not found in public.ts");
  const { art } = genMaps();
  out = out.replace(artRe, `if(typeof MC_ART!=="undefined")MC_ART={${art}};`);

  // 3) mcFitScan head (querySelectorAll ... MC_GEOM lookup) — tolerant of
  //    the generated SCAN-START marker so re-running stays idempotent
  const scanRe = /var mcFitScan=function\(\)\{\n(?:\/\*MC-HEROES:SCAN-START \(generated\)\*\/\n)?document\.querySelectorAll\("\.hero-mcard \.mc-port img"\)\.forEach\(function\(im\)\{\nvar (?:g=MC_GEOM\[im\.getAttribute\("src"\)\]|s0=im\.getAttribute\("src"\),tw=MC_SIDE\[s0\];[\s\S]*?var g=MC_GEOM\[s0\]);/;
  if (!scanRe.test(out)) throw new Error("mcFitScan head not found in public.ts");
  out = out.replace(scanRe, "@@MC_HEROES_SCAN@@");

  // substitute placeholders
  const block = genBlock();
  out = out.replace("@@MC_HEROES_BLOCK@@", block);
  out = out.replace("@@MC_HEROES_SCAN@@", genScanHead());
  return out;
}

function checkSync(src) {
  const { art, geom, side, homeSet } = genMaps();
  const problems = [];
  if (!src.includes(`MC_ART={${art}}`)) problems.push("MC_ART map out of sync");
  if (!src.includes(`var MC_GEOM={${geom}};`)) problems.push("MC_GEOM map out of sync");
  if (!src.includes(`var MC_SIDE={${side}};`)) problems.push("MC_SIDE map out of sync");
  if (!src.includes(`var MC_HOME_SRC={${homeSet}};`)) problems.push("MC_HOME_SRC map out of sync");
  if (!src.includes(`if(wa===ih){im.setAttribute("src",tw);s0=tw}`)) problems.push("mcFitScan side-swap missing");
  return problems;
}

function main() {
  const check = process.argv.includes("--check");
  const src = readPage();
  if (check) {
    const problems = checkSync(src);
    if (problems.length) {
      console.error("FAIL wire --check: " + problems.join("; ") + " — run: node scripts/mc-heroes/wire.js");
      process.exit(1);
    }
    console.log("OK   wire --check: public.ts MC-HEROES blocks in sync with mc-heroes.json");
    return;
  }
  const out = applyWrite(src);
  if (out === src) { console.log("OK   wire: no changes"); return; }
  fs.writeFileSync(PAGE, out);
  const problems = checkSync(out);
  if (problems.length) throw new Error("post-write verification failed: " + problems.join("; "));
  console.log("OK   wire: public.ts updated (" + Object.keys(REG.clubs).length + " clubs, " +
    Object.values(REG.clubs).reduce((n, e) => n + (e.away ? 2 : 1), 0) + " variant files)");
}

main();
