#!/usr/bin/env node
// refactor-client-core.mjs — builds src/pages/client-core.ts from the three
// page templates: merges the ×3 I18N dictionaries into ONE unified dict
// (public's values win; admin's 25 unique keys join), dedupes the ×3 copies
// of the 10 theme/lang client helpers, and rewrites the three page modules to
// interpolate the shared core. Also dedupes the ×3 favicon block in the
// public page head.
import fs from "node:fs";

const esc = (s) => JSON.stringify(s).replace(/[\u007f-\uffff]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
const escKey = (k) => /^[A-Za-z_$][\w$]*$/.test(k) ? k : esc(k);

function serialize(obj, indent) {
  if (obj === null || typeof obj !== "object") return esc(obj);
  const isArr = Array.isArray(obj);
  const parts = isArr ? obj.map((v) => serialize(v)) : Object.entries(obj).map(([k, v]) => escKey(k) + ":" + serialize(v));
  return isArr ? "[" + parts.join(",") + "]" : "{" + parts.join(",") + "}";
}

// ---------- grab from current pages ----------
function grabI18N(file) {
  const c = fs.readFileSync(file, "utf8");
  const i = c.indexOf("var I18N={");
  if (i < 0) throw new Error("I18N not found in " + file);
  let depth = 0, j = i + "var I18N=".length - 1;
  for (; j < c.length; j++) {
    if (c[j] === "{") depth++;
    else if (c[j] === "}") { depth--; if (depth === 0) break; }
  }
  return { start: i, end: j + 1, text: c.slice(i, j + 1) };
}
function grabFn(c, name) {
  const i = c.indexOf("function " + name + "(");
  if (i < 0) throw new Error("fn not found: " + name);
  let depth = 0, j = c.indexOf("{", i);
  for (; j < c.length; j++) {
    if (c[j] === "{") depth++;
    else if (c[j] === "}") { depth--; if (depth === 0) break; }
  }
  return { start: i, end: j + 1, text: c.slice(i, j + 1) };
}

const HELPERS = ["curLang", "T", "fmt", "trText", "trPlace", "initTheme", "setTheme", "toggleTheme", "switchLang", "applyLang"];

const pubP = "src/pages/public.ts", logP = "src/pages/login.ts", admP = "src/pages/admin.ts";
const pubC = fs.readFileSync(pubP, "utf8"), logC = fs.readFileSync(logP, "utf8"), admC = fs.readFileSync(admP, "utf8");

const pubI = grabI18N(pubP), logI = grabI18N(logP);
const P = eval("(" + pubI.text.replace(/^var I18N=/, "") + ")");
const L = eval("(" + logI.text.replace(/^var I18N=/, "") + ")");

// unified: PUBLIC wins conflicts (cupsNone/comps — login's values are
// vestigial: cupsNone is unused in login/admin; comps differs in key order
// only), LOGIN/ADMIN's unique admin-panel keys join.
const unified = { fa: { ...L.fa, ...P.fa }, en: { ...L.en, ...P.en } };
const nFa = Object.keys(unified.fa).length, nEn = Object.keys(unified.en).length;

// helpers — from public (byte-identical in all three)
const helperTexts = HELPERS.map((h) => grabFn(pubC, h).text);

// ---------- write client-core.ts ----------
const core = `// SportSignal — shared CLIENT-side core for all three pages (public, login,
// admin): the unified bilingual I18N dictionary + the theme/language helper
// functions. ONE source of truth — previously the bundle shipped three
// diverged copies (~19-23KB each). Generated by
// scripts/refactor-client-core.mjs; edit the generator, not this file.

export const I18N = ${serialize(unified, 0)};

export const CLIENT_CORE_JS =
"var I18N=" + ${JSON.stringify(serialize(unified, 0))} + ";\\n" +
${helperTexts.map((t) => JSON.stringify(t)).join(" +\n")};
`;
fs.writeFileSync("src/pages/client-core.ts", core);
console.log(`client-core.ts written: ${Object.keys(unified.fa).length} fa keys, ${Object.keys(unified.en).length} en keys, ${core.length} bytes`);

// ---------- rewrite pages: drop dict + helpers, interpolate core ----------
function rewritePage(path, content) {
  let c = content;
  // remove I18N dict line
  const i18 = grabI18N(path);
  c = c.slice(0, i18.start) + "${CLIENT_CORE_JS}" + c.slice(i18.end);
  // remove helper functions (first occurrence each)
  for (const h of HELPERS) {
    const g = grabFn(c, h);
    // remove the function + its trailing newline
    let end = g.end;
    while (c[end] === "\n" || c[end] === " ") end++;
    c = c.slice(0, g.start) + c.slice(end);
  }
  // add import of CLIENT_CORE_JS (pages already import from ../config)
  if (!c.includes("CLIENT_CORE_JS")) throw new Error("interpolation missing");
  c = c.replace('import {', 'import { CLIENT_CORE_JS } from "./client-core";\nimport {', 1);
  fs.writeFileSync(path, c);
  return c;
}
rewritePage(pubP, pubC);
rewritePage(logP, logC);
rewritePage(admP, admC);
console.log("pages rewritten with ${CLIENT_CORE_JS} interpolation");

// ---------- dedupe favicon block in public head (was ×3) ----------
let pub2 = fs.readFileSync(pubP, "utf8");
const fav = `<link rel="icon" href="/favicon.ico" sizes="any">
<link rel="icon" type="image/png" sizes="32x32" href="/favicon-32x32.png">
<link rel="icon" type="image/png" sizes="16x16" href="/favicon-16x16.png">
<link rel="apple-touch-icon" sizes="180x180" href="/apple-touch-icon.png">
<link rel="manifest" href="/site.webmanifest">
<meta name="theme-color" content="#0f172a">
<meta name="apple-mobile-web-app-title" content="SportSignal">
<meta name="application-name" content="SportSignal">
`;
const count = pub2.split(fav).length - 1;
if (count === 3) {
  pub2 = pub2.replace(fav + fav + fav, fav);
  fs.writeFileSync(pubP, pub2);
  console.log("favicon block deduped (x3 -> x1)");
} else {
  console.log("favicon block occurrences:", count, "(expected 3) — leaving as-is");
}
